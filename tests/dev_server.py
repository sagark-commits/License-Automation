"""Local DEV server with a fake database - for looking at the UI, never for production.

    python tests/dev_server.py            # http://127.0.0.1:8099   users: admin1 / oper1 / view1  (password below)

Reports are generated by the real engine against synthetic data (tests/scenario.py).
"""
import copy
import os
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path[:0] = [str(ROOT), str(HERE)]

import fakedb                                    # noqa: E402
from scenario import DEFAULTS, TENANTS, build_world   # noqa: E402

PASSWORD = "Dev-only-password-1"


class _Patch:
    """Minimal stand-in for pytest's monkeypatch."""

    def setattr(self, target, name, value=None, **_kw):
        if value is None and isinstance(target, str):
            raise TypeError("string targets are not supported")
        setattr(target, name, value)


class _StubCursor:
    def __init__(self, conn):
        self.conn, self.rows = conn, []

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False

    def execute(self, sql, params=None):
        s = " ".join(sql.split())
        if "FROM contact_center" in s:
            self.rows = [("Acme Corporation Malaysia",)]
        elif "GROUP BY d.user_type" in s:
            self.rows = [("Professional-Agent", 1840, 22, "2026-10-20"), ("Ameyo-Pro", 410, 6, "2026-10-20"), ("Supervisor", 230, 4, "2026-10-20"), ("Administrator", 12, 1, "2026-10-02")]
        elif "information_schema" in s:
            self.rows = [("id",), ("name",)]
        elif "FROM campaign_context" in s:
            self.rows = [(5, "Welcome calls"), (9, "Retention")]
        elif "ILIKE" in s:
            self.rows = [("ACME_wallboard", "Wallboard")]
        elif "version()" in s:
            self.rows = [("PostgreSQL 14.17, compiled by dev",)]
        elif "transaction_read_only" in s:
            self.rows = [("on",)]
        elif "to_regclass" in s:
            self.rows = [("x",)]
        else:
            self.rows = []

    def fetchall(self):
        return self.rows


class _StubConn:
    def cursor(self):
        return _StubCursor(self)

    def close(self):
        pass


def main() -> None:
    import db_connections
    from lic_web.server import configure_logging, serve
    from lic_web.wiring import create_app

    world = build_world()
    fakedb.install(world, _Patch())
    db_connections.connect_database = lambda settings: _StubConn()

    data_dir = Path(os.environ.get("LIC_DEV_DATA") or tempfile.mkdtemp(prefix="lic-dev-"))
    configure_logging(None)
    app = create_app(data_dir, ROOT)
    tenants = copy.deepcopy(TENANTS)
    tenants["ALPHA"]["campaign_ids"] = []
    app.data.save_registry({"defaults": copy.deepcopy(DEFAULTS), "tenants": tenants}, "dev")
    for arc in ("ARC-1", "ARC-2"):
        app.data.save_db(arc, {"host": "10.28.9.%d" % (103 if arc == "ARC-1" else 110), "port": 5432, "name": "oneproduct", "user": "report_ro", "password": "dev-only"}, "dev")
    for name, role in (("admin1", "admin"), ("oper1", "operator"), ("view1", "viewer")):
        try:
            app.users.create(name, PASSWORD, role)
        except ValueError:
            pass
    print("DEV server - data in %s - sign in as admin1 / oper1 / view1 with password %s" % (data_dir, PASSWORD))
    serve(app, "127.0.0.1", int(os.environ.get("PORT", "8099")))


if __name__ == "__main__":
    main()
